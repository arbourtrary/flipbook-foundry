import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { buildFont } from '../src/lib/font/buildFont.ts';
import { exportWoff2 } from '../src/lib/font/exportWoff2.ts';
import type { PosesManifest } from '../src/lib/font/types.ts';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, '..');
const posesDir = join(repoRoot, 'src/poses');
const manifestPath = join(repoRoot, 'src/lib/font/poses.json');
const outDir = join(repoRoot, 'static/fonts');

async function main() {
	const manifest = JSON.parse(await readFile(manifestPath, 'utf8')) as PosesManifest;

	const font = await buildFont(manifest, (file) => readFile(join(posesDir, file), 'utf8'));
	const otf = new Uint8Array(font.toArrayBuffer());
	const woff2 = await exportWoff2(otf);

	await mkdir(outDir, { recursive: true });
	await writeFile(join(outDir, 'flipbook.otf'), otf);
	await writeFile(join(outDir, 'flipbook.woff2'), woff2);

	const hash = createHash('sha256').update(woff2).digest('hex').slice(0, 10);
	const versionTs = `// Generated by scripts/build-font.ts — do not edit by hand.\nexport const FONT_VERSION = '${hash}';\n`;
	await writeFile(join(repoRoot, 'src/lib/font/font-version.ts'), versionTs, 'utf8');

	console.log(
		`Built ${manifest.poses.length} pose(s) → ${otf.byteLength} B .otf / ${woff2.byteLength} B .woff2 (v${hash})`
	);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
