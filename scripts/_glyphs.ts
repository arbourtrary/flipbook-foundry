import { chromium } from 'playwright-core';
import { homedir } from 'node:os';
import { join } from 'node:path';
import m from '../src/lib/flipbook/generated/manifest.json' with { type: 'json' };
const [name = 'jump', from = '10', to = '18', out = '.sheets/glyphs.png'] = process.argv.slice(2);
const a = (m as any).actions[name];
let html = `<style>@font-face{font-family:F;src:url(http://localhost:5199/fonts/flipbook-regular.woff2?${Date.now()})}body{margin:0;background:#fff}span{font:420px F;display:inline-block;border-bottom:1px solid #ccc;margin:0 4px;padding-top:300px}</style>`;
for (let i = +from; i <= +to; i++) html += `<span>${String.fromCharCode(a.start + i)}</span>`;
const b = await chromium.launch({ executablePath: join(homedir(), 'Library/Caches/ms-playwright/chromium-1217/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'), args: ['--headless=new'] });
const p = await b.newPage({ viewport: { width: 1400, height: 400 } });
await p.setContent(html);
await p.waitForTimeout(800);
await p.screenshot({ path: out, fullPage: true });
await b.close();
console.log(out);
